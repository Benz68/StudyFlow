import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.STUDYFLOW_PLAYWRIGHT||'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},locale:'he-IL',timezoneId:'Asia/Jerusalem',reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('studyflow.fresh.v1')));
const submit=()=>page.locator('#add-form button[type=submit]').click();
try{
 await page.clock.install({time:new Date('2026-09-30T08:00:00+03:00')});
 await page.goto('http://127.0.0.1:4173');
 await page.locator('[data-action=add]:visible').first().click();
 await page.locator('[data-form-tab=event]').click();
 await page.locator('#title').fill('שיעור קבוע');
 await page.locator('#repeatMode').selectOption('year');
 assert.match(await page.locator('#repeat-summary').textContent(),/תיפסק אוטומטית/);
 await page.locator('[name=weekdays][value="4"]').check();
 await submit();
 let event=(await stored()).events[0];
 assert.equal(event.repeatUntil,'2027-09-29');assert.deepEqual(event.weekdays,[3,4]);
 await page.locator('[data-action=delete-event]').first().click();
 await page.locator('[data-action=remove-occurrence]').click();
 assert.deepEqual((await stored()).events[0].excludedDates,['2026-09-30']);
 await page.reload();
 assert.equal(await page.locator('.fixed-card').count(),0);
 await page.locator('[data-date="2026-10-01"]').click();
 await page.locator('.fixed-card').waitFor();
 await page.locator('[data-action=edit-event]').click();
 await page.locator('#repeatMode').selectOption('weeks');
 await page.locator('#weeksCount').fill('2');
 await submit();
 assert.equal((await stored()).events[0].repeatUntil,'2026-10-13');
 assert.deepEqual((await stored()).events[0].excludedDates,['2026-09-30']);
 await page.locator('[data-action=settings]:visible').first().click();
 await page.locator('#preferredTime').selectOption('evening');
 await page.locator('#scheduleStyle').selectOption('balanced');
 await page.locator('[name=preferredDays][value="4"]').check();
 await page.locator('[name=allowOutsidePreferred]').uncheck();
 await page.locator('#settings-form button[type=submit]').click();
 await page.locator('[data-action=add]:visible').first().click();
 await page.locator('#title').fill('ללמוד בזמן שלי');
 await submit();
 await page.locator('[data-view=week]:visible').click();
 const flexible=page.locator('.agenda-item:not(.fixed)');
 assert.ok(await flexible.count()>0);
 for(const text of await flexible.locator('span').allTextContents())assert.ok(text>='17:00');
 const prefs=(await stored()).preferences;
 assert.equal(prefs.preferredTime,'evening');assert.equal(prefs.allowOutsidePreferred,false);
 await page.locator('[data-view=tasks]:visible').click();
 await page.locator('.commitments [data-action=delete-event]').click();
 assert.equal(await page.locator('[data-action=remove-occurrence]').count(),0,'Series list must not target an arbitrary date');
 await page.locator('[data-action=remove-series]').click();
 assert.equal((await stored()).events.length,0);
 await page.locator('[data-action=undo]').click();
 assert.equal((await stored()).events.length,1);
 await page.reload();assert.equal((await stored()).preferences.preferredTime,'evening');
 await page.locator('[data-view=tasks]:visible').click();
 await page.locator('.commitments [data-action=edit-event]').click();
 await page.locator('[data-action=stop-series]').click();
 await page.locator('[data-action=confirm-stop-series]').click();
 assert.equal((await stored()).events.length,0,'Stopping a series starting today removes future occurrences');
 await page.locator('[data-action=undo]').click();
 await page.evaluate(()=>{const data=JSON.parse(localStorage.getItem('studyflow.fresh.v1'));data.events[0].date='2026-09-01';localStorage.setItem('studyflow.fresh.v1',JSON.stringify(data));});
 await page.reload();
 await page.locator('[data-view=tasks]:visible').click();
 await page.locator('.commitments [data-action=edit-event]').click();
 await page.locator('[data-action=stop-series]').click();
 await page.locator('[data-action=confirm-stop-series]').click();
 assert.equal((await stored()).events[0].repeatUntil,'2026-09-29','Stopping preserves earlier series history');
 assert.deepEqual((await stored()).events[0].excludedDates,['2026-09-30']);
 await page.reload();
 assert.equal(await page.locator('.fixed-card').count(),0);
 assert.equal(await page.locator('.sculpture-body').evaluate(el=>getComputedStyle(el).animationName),'none');
 await page.emulateMedia({reducedMotion:'no-preference'});
 assert.equal(await page.locator('.sculpture-body').evaluate(el=>getComputedStyle(el).animationName),'sculpture-drift');
 await page.locator('[data-date="2026-10-01"]').click();
 await page.locator('[data-action=complete-session]').first().click();
 assert.equal(await page.locator('.completion-burst').count(),9);
 await page.clock.runFor(800);
 assert.equal(await page.locator('.completion-burst').count(),0,'Completion particles clean themselves up');
 assert.deepEqual(errors,[]);
 console.log('Year/weeks, selected weekdays, single occurrence, series editing/removal/undo, strict evening preference and reload passed.');
}finally{await browser.close();}
