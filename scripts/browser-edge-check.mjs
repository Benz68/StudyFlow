import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.STUDYFLOW_PLAYWRIGHT||'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:360,height:800},locale:'he-IL',timezoneId:'Asia/Jerusalem',reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('studyflow.fresh.v1')));
const add=async title=>{await page.locator('[data-action="add"]:visible').first().click();await page.locator('#title').fill(title);};
const submit=()=>page.locator('#add-form button[type="submit"]').click();
try{
 await page.clock.install({time:new Date('2026-09-30T08:00:00+03:00')});
 await page.goto('http://127.0.0.1:4173');
 await page.locator('#main h1').waitFor();
 await page.locator('[data-action="demo"]').click();
 assert.equal(await stored(),null,'Demo does not write real storage');
 await page.locator('[data-action="complete-session"]').first().click();
 assert.equal(await stored(),null,'Demo mutations stay isolated');
 await page.locator('[data-action="exit-demo"]').click();
 await add('עבודה להגשה');
 await page.locator('#minutes').fill('120');
 await page.locator('#deadline').fill('2026-09-30');
 await submit();
 await page.locator('[data-action="add"]:visible').first().click();
 await page.locator('[data-form-tab="event"]').click();
 await page.locator('#title').fill('הרצאה חוזרת');
 await page.locator('#start').fill('09:00');
 await page.locator('#end').fill('11:00');
 await page.locator('[name="repeat"]').check();
 await submit();
 assert.equal((await stored()).events[0].repeat,'weekly');
 const firstTime=await page.locator('.timeline-row').filter({has:page.locator('[data-action="complete-session"]')}).first().locator('.time b').textContent();
 assert.equal(firstTime,'11:00','Recurring event blocks scheduling');
 await page.locator('[data-action="delay"]').first().click();
 assert.ok((await stored()).tasks[0].notBefore.includes('09:00'),'Delayed beyond scheduled slot, not merely current time');
 await page.locator('[data-action="undo"]').click();
 assert.equal((await stored()).tasks[0].notBefore,undefined);
 await page.locator('[data-view="tasks"]:visible').click();
 await page.locator('[data-action="edit-task"]').first().click();
 await page.locator('#title').fill('עבודה מעודכנת');
 await page.locator('#minutes').fill('180');
 await submit();
 assert.equal((await stored()).tasks[0].minutes,180);
 await page.locator('[data-action="settings"]:visible').first().click();
 await page.locator('#maxDailyMinutes').selectOption('60');
 await page.locator('#settings-form button[type="submit"]').click();
 await page.locator('.overflow-card').waitFor();
 assert.ok(await page.locator('.overflow-card [data-action="edit-task"]').count()>0,'Infeasibility has a recovery action');
 await add('<img src=x onerror="window.pwned=1">');
 await submit();
 assert.equal(await page.evaluate(()=>window.pwned),undefined);
 assert.equal(await page.locator('#main img').count(),0,'User titles rendered as text');
 await page.locator('[data-action="settings"]:visible').first().click();
 const before=JSON.stringify(await stored());
 await page.locator('#import-file').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{"tasks":[{}],"events":[]}')});
 await page.getByText('לא הצלחנו לקרוא את הגיבוי. יש לבחור קובץ גיבוי תקין של StudyFlow.').waitFor({state:'attached'});
 assert.equal(JSON.stringify(await stored()),before,'Invalid import cannot erase data');
 await page.keyboard.press('Escape');
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await context.setOffline(true);
 await page.reload();
 await page.locator('#main h1').waitFor();
 assert.equal((await stored()).tasks.length,2,'App and user data survive offline reload');
 await context.setOffline(false);
 for(const width of [320,390,768,1440]){
  await page.setViewportSize({width,height:850});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`No overflow at ${width}`);
 }
 assert.deepEqual(errors,[]);
 console.log('Recurring events, delay/undo, editing, capacity recovery, safe titles, import rejection, offline, responsive checks passed.');
}finally{await browser.close();}
